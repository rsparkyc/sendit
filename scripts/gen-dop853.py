"""Emit the Dormand-Prince 8(5,3) tableau as TypeScript, taken from SciPy.

Python's repr() of a float round-trips exactly to the same IEEE-754 double in
JavaScript, so the generated literals are bit-identical to SciPy's.
"""
from scipy.integrate._ivp import dop853_coefficients as c

N = c.N_STAGES  # 12


def arr(xs):
    return "[" + ", ".join(repr(float(x)) for x in xs) + "]"


print("// GENERATED by scripts/gen-dop853.py from scipy.integrate._ivp.dop853_coefficients.")
print("// Do not edit by hand.")
print()
print(f"export const N_STAGES = {N};")
print(f"export const C: readonly number[] = {arr(c.C[:N])};")
print("export const A: readonly (readonly number[])[] = [")
for s in range(N):
    print(f"  {arr(c.A[s, :s])},")
print("];")
print(f"export const B: readonly number[] = {arr(c.B)};")
print(f"export const E3: readonly number[] = {arr(c.E3)};")
print(f"export const E5: readonly number[] = {arr(c.E5)};")
print()
print("// Dense output (SciPy DOP853._dense_output_impl): three extra stages, evaluated")
print("// after an accepted step, at indices N_STAGES+1 .. N_STAGES_EXTENDED-1.")
NX = c.N_STAGES_EXTENDED  # 16
print(f"export const N_STAGES_EXTENDED = {NX};")
print(f"export const INTERPOLATOR_POWER = {c.INTERPOLATOR_POWER};")
print(f"export const C_EXTRA: readonly number[] = {arr(c.C[N + 1:NX])};")
print("export const A_EXTRA: readonly (readonly number[])[] = [")
for s in range(N + 1, NX):
    print(f"  {arr(c.A[s, :s])},")
print("];")
print("/** Rows map the 16 extended stages onto interpolant coefficients F[3..6]. */")
print("export const D: readonly (readonly number[])[] = [")
for row in c.D:
    print(f"  {arr(row)},")
print("];")
