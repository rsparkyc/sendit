#!/usr/bin/env python3
"""Generate core/src/dop853_coefficients.rs from src/physics/dop853-coefficients.ts.

The literal decimal strings are copied verbatim (not re-printed), so Rust parses
exactly the text the TypeScript parses; both round to the nearest double.
Run from the repository root: python3 core/scripts/gen-dop853-rs.py > core/src/dop853_coefficients.rs
"""
import re

src = open('src/physics/dop853-coefficients.ts').read()

def arr(name):
    m = re.search(r'export const ' + name + r'\b[^=]*=\s*(\[.*?\]);', src, re.S)
    return m.group(1)

def rows(text):
    inner = text.strip()[1:-1]
    return [r for r in re.findall(r'\[([^\[\]]*)\]', inner)]

def nums(s):
    return [x.strip() for x in s.split(',') if x.strip()]

def lit(x):
    return x if ('.' in x or 'e' in x) else x + '.0'

out = ['// GENERATED by core/scripts/gen-dop853-rs.py from src/physics/dop853-coefficients.ts. Do not edit.', '']
for name in ['C', 'B', 'E3', 'E5', 'C_EXTRA']:
    v = nums(arr(name)[1:-1])
    out.append(f'pub const {name}: [f64; {len(v)}] = [{", ".join(lit(x) for x in v)}];')
for name in ['A', 'A_EXTRA', 'D']:
    rs = rows(arr(name))
    out.append(f'pub const {name}: &[&[f64]] = &[')
    for r in rs:
        out.append('    &[' + ', '.join(lit(x) for x in nums(r)) + '],')
    out.append('];')
for name in ['N_STAGES', 'N_STAGES_EXTENDED', 'INTERPOLATOR_POWER']:
    m = re.search(r'export const ' + name + r' = (\d+);', src)
    out.append(f'pub const {name}: usize = {m.group(1)};')
print('\n'.join(out))
